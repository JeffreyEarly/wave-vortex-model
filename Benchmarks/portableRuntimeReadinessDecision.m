function decision = portableRuntimeReadinessDecision(comparison)
% Apply the standalone runtime's integration-only speed and memory gates.
arguments
    comparison (:,1) struct
end
complete = ~isempty(comparison) && all(string({comparison.status}) == "complete");
correct = complete && all([comparison.maximumRelativeError] <= 1e-12);
identity = complete && all([comparison.nativeIdentityPassed]) && all([comparison.noFallback]) && all([comparison.planCount] == 17) && all([comparison.persistentFullHermitianBytes] == 0);
speedQualified = complete && all([comparison.integrationSpeedup] >= 1.25);
memoryOptimized = complete && all([comparison.peakIncrementRSSRatio] <= 0.80);
previewReady = correct && identity && speedQualified;
decision = struct( ...
    "status",conditional(previewReady,"RUNTIME-PREVIEW-READY","RUNTIME-PREVIEW-NOT-READY"), ...
    "previewReady",previewReady, ...
    "memoryStatus",conditional(memoryOptimized,"RUNTIME-MEMORY-OPTIMIZED","RUNTIME-MEMORY-NOT-OPTIMIZED"), ...
    "memoryOptimized",memoryOptimized, ...
    "integrationSpeedThreshold",1.25, ...
    "peakIncrementRSSRatioThreshold",0.80, ...
    "correctnessTolerance",1e-12, ...
    "timingScope","eight fixed RK4 integration steps only; construction, preparation, checkpoint I/O, and output writing excluded");
end

function value = conditional(condition,trueValue,falseValue)
if condition, value = trueValue; else, value = falseValue; end
end
