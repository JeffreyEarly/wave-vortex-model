function results = runCompiledKernelCoefficientAssemblyConfirmationBenchmark(options)
% Confirm the clean issue #126 implementation against the issue #137 baseline.
arguments
    options.baselineArtifact (1,1) string = defaultBaselineArtifact
    options.processRunCount (1,1) double {mustBeInteger,mustBePositive} = 3
    options.threadCount (1,1) double {mustBeInteger,mustBePositive} = 18
    options.warmupCount (1,1) double {mustBeInteger,mustBeNonnegative} = 2
    options.mediumSampleCount (1,1) double {mustBeInteger,mustBePositive} = 7
    options.largeSampleCount (1,1) double {mustBeInteger,mustBePositive} = 3
    options.samplingIntervalSeconds (1,1) double {mustBePositive} = 0.02
    options.plateauSeconds (1,1) double {mustBePositive} = 0.12
    options.outputDirectory (1,1) string = ""
    options.runId (1,1) string = string(datetime("now","TimeZone","UTC","Format","yyyyMMdd'T'HHmmssSSS'Z'"))
    options.shouldWriteArtifacts (1,1) logical = true
    options.requireCleanCandidate (1,1) logical = true
end

benchmarkFolder = string(fileparts(mfilename("fullpath")));
repositoryRoot = string(fileparts(benchmarkFolder));
[candidateCommit,candidateTree,candidateDirty] = gitIdentity(repositoryRoot);
if options.requireCleanCandidate && candidateDirty
    error("WaveVortexModel:DirtyCoefficientAssemblyConfirmation","The clean issue #126 confirmation requires a clean tracked tree.");
end
if ~isfile(options.baselineArtifact)
    error("WaveVortexModel:CoefficientAssemblyBaselineMissing","The issue #137 baseline artifact is missing: %s",options.baselineArtifact);
end

raw = runCompiledKernelNativeFFTWBenchmark( ...
    threadCounts=options.threadCount, ...
    providerIds="native-neon-pthreads", ...
    screeningWarmupCount=0, ...
    screeningMediumSampleCount=1, ...
    screeningLargeSampleCount=1, ...
    finalWarmupCount=options.warmupCount, ...
    finalMediumSampleCount=options.mediumSampleCount, ...
    finalLargeSampleCount=options.largeSampleCount, ...
    finalProcessRunCount=options.processRunCount, ...
    samplingIntervalSeconds=options.samplingIntervalSeconds, ...
    plateauSeconds=options.plateauSeconds, ...
    shouldIncludeBundledControl=false, ...
    shouldWriteArtifacts=false);
current = raw.finalConfigurations(string({raw.finalConfigurations.providerId})=="native-neon-pthreads" & [raw.finalConfigurations.threadCount]==options.threadCount);
if numel(current) ~= 1
    error("WaveVortexModel:CoefficientAssemblyCandidateMissing","The clean candidate did not produce exactly one native NEON/pthreads configuration.");
end
baseline = jsondecode(fileread(options.baselineArtifact));
baselineConfiguration = baseline.finalConfigurations(string({baseline.finalConfigurations.providerId})=="native-neon-pthreads" & [baseline.finalConfigurations.threadCount]==options.threadCount);
if numel(baselineConfiguration) ~= 1
    error("WaveVortexModel:CoefficientAssemblyBaselineMissing","The issue #137 artifact does not contain the selected native NEON/pthreads configuration.");
end

cases = comparisonCases(baselineConfiguration,current);
decision = compiledKernelCoefficientAssemblyConfirmationDecision(cases);
metadataPassed = all(arrayfun(@candidateMetadataPassed,current.cases));
results = struct( ...
    "schemaVersion","1.0.0", ...
    "status",conditional(raw.status=="complete" && decision.confirmed && metadataPassed,"complete","failed"), ...
    "runId",options.runId, ...
    "generatedAtUTC",utcTimestamp, ...
    "source",struct( ...
        "repository","JeffreyEarly/wave-vortex-model", ...
        "candidateCommit",candidateCommit, ...
        "candidateTree",candidateTree, ...
        "candidateDirty",candidateDirty, ...
        "sourceHashes",sourceHashes(repositoryRoot), ...
        "baselineArtifact",relativePath(options.baselineArtifact,repositoryRoot), ...
        "baselineArtifactSha256",sha256File(options.baselineArtifact), ...
        "baselineCommit",string(baseline.source.commit)), ...
    "configuration",struct( ...
        "provider","native-neon-pthreads", ...
        "threadCount",options.threadCount, ...
        "processRunCount",options.processRunCount, ...
        "warmupCount",options.warmupCount, ...
        "mediumSampleCount",options.mediumSampleCount, ...
        "largeSampleCount",options.largeSampleCount, ...
        "correctnessTolerance",1e-12, ...
        "maximumRegression",0.03, ...
        "minimumDescriptorReduction",0.10, ...
        "minimumCleanSpeedup",1.05), ...
    "provider",struct( ...
        "id",string(current.providerId), ...
        "threadBackend",string(current.threadBackend), ...
        "threadCount",current.threadCount, ...
        "baseLibrary",string(current.runs(1).moduleInfo.baseLibrary), ...
        "threadLibrary",string(current.runs(1).moduleInfo.threadLibrary)), ...
    "cases",cases, ...
    "metadataPassed",metadataPassed, ...
    "decision",decision, ...
    "currentRuns",current.runs);

if options.outputDirectory == ""
    options.outputDirectory = fullfile(benchmarkFolder,"results","experiments","issue126-native-clean",options.runId+"-"+computer("arch")+"-r"+lower(version("-release")));
end
if options.shouldWriteArtifacts
    if isfolder(options.outputDirectory)
        error("WaveVortexModel:CoefficientAssemblyConfirmationOutputExists","Output already exists: %s",options.outputDirectory);
    end
    mkdir(options.outputDirectory);
    writeText(fullfile(options.outputDirectory,"coefficient-assembly-confirmation.json"),jsonencode(results,PrettyPrint=true));
    writeText(fullfile(options.outputDirectory,"summary.md"),summaryMarkdown(results));
end
end

function cases = comparisonCases(baseline,current)
cases = repmat(struct("id","","Nxyz",[],"isHydrostatic",false,"baselineTotalSeconds",NaN,"candidateTotalSeconds",NaN,"completeCallSpeedup",NaN,"baselineInternalSeconds",NaN,"candidateInternalSeconds",NaN,"internalSpeedup",NaN,"baselineDescriptorBytes",NaN,"candidateDescriptorBytes",NaN,"descriptorReduction",NaN,"baselineMaximumLiveBytes",NaN,"candidateMaximumLiveBytes",NaN,"maximumLiveReduction",NaN,"candidatePeakIncrementRSSBytes",[],"maximumRelativeError",NaN,"lifecyclePassed",false),numel(current.cases),1);
for iCase = 1:numel(current.cases)
    candidateCase = current.cases(iCase);
    baselineCase = baseline.cases(string({baseline.cases.id})==string(candidateCase.id));
    if numel(baselineCase) ~= 1
        error("WaveVortexModel:CoefficientAssemblyCaseMismatch","The issue #137 artifact does not contain %s.",candidateCase.id);
    end
    baselineTotal = baselineCase.medianTotalSeconds.nonlinearFlux;
    candidateTotal = candidateCase.medianTotalSeconds.nonlinearFlux;
    baselineInternal = baselineCase.medianInternalSeconds.nonlinearFlux;
    candidateInternal = candidateCase.medianInternalSeconds.nonlinearFlux;
    baselineDescriptor = baselineCase.metrics.descriptorBytes;
    candidateDescriptor = candidateCase.metrics.descriptorBytes;
    baselineMaximumLive = baselineCase.metrics.knownMaximumLiveOwnedBytes;
    candidateMaximumLive = candidateCase.metrics.knownMaximumLiveOwnedBytes;
    definition = parseCaseId(string(candidateCase.id));
    cases(iCase) = struct( ...
        "id",string(candidateCase.id), ...
        "Nxyz",definition.Nxyz, ...
        "isHydrostatic",definition.isHydrostatic, ...
        "baselineTotalSeconds",baselineTotal, ...
        "candidateTotalSeconds",candidateTotal, ...
        "completeCallSpeedup",baselineTotal/candidateTotal, ...
        "baselineInternalSeconds",baselineInternal, ...
        "candidateInternalSeconds",candidateInternal, ...
        "internalSpeedup",baselineInternal/candidateInternal, ...
        "baselineDescriptorBytes",baselineDescriptor, ...
        "candidateDescriptorBytes",candidateDescriptor, ...
        "descriptorReduction",1-candidateDescriptor/baselineDescriptor, ...
        "baselineMaximumLiveBytes",baselineMaximumLive, ...
        "candidateMaximumLiveBytes",candidateMaximumLive, ...
        "maximumLiveReduction",1-candidateMaximumLive/baselineMaximumLive, ...
        "candidatePeakIncrementRSSBytes",candidateCase.peakIncrementRSSBytes, ...
        "maximumRelativeError",candidateCase.maximumRelativeError, ...
        "lifecyclePassed",current.lifecyclePassed);
end
end

function passed = candidateMetadataPassed(candidateCase)
metrics = candidateCase.metrics;
passed = metrics.contractVersion==4 && ...
    string(metrics.coefficientStorageMode)=="natural-dimensional" && ...
    string(metrics.coefficientArithmeticMode)=="natural-dimensional-prescaled" && ...
    string(metrics.optimizationImplementation)=="O3-native" && ...
    metrics.coefficientWorkerCount==2;
end

function definition = parseCaseId(identifier)
tokens = regexp(identifier,"constant-(hydrostatic|nonhydrostatic)-(\d+)x(\d+)x(\d+)","tokens","once");
if isempty(tokens)
    error("WaveVortexModel:CoefficientAssemblyCaseIdentifier","Unrecognized core-v1 case identifier: %s",identifier);
end
definition = struct("isHydrostatic",tokens{1}=="hydrostatic","Nxyz",str2double(tokens(2:4)));
end

function markdown = summaryMarkdown(results)
lines = [ ...
    "# Clean issue #126 coefficient-assembly confirmation"; ...
    ""; ...
    "- Status: `"+results.status+"`"; ...
    "- Candidate: `"+results.source.candidateCommit+"`"; ...
    "- Baseline: `"+results.source.baselineCommit+"`"; ...
    "- Provider: `"+results.provider.id+"`, "+results.provider.threadCount+" FFTW threads"; ...
    "- Decision: `"+results.decision.status+"`"; ...
    ""; ...
    "| Case | Baseline total (ms) | Candidate total (ms) | Speedup | Descriptor reduction | Max-live reduction | Error |"; ...
    "|---|---:|---:|---:|---:|---:|---:|"];
for item = results.cases'
    lines(end+1) = sprintf("| %s | %.3f | %.3f | %.3fx | %.2f%% | %.2f%% | %.3e |",item.id,1e3*item.baselineTotalSeconds,1e3*item.candidateTotalSeconds,item.completeCallSpeedup,100*item.descriptorReduction,100*item.maximumLiveReduction,item.maximumRelativeError); %#ok<AGROW>
end
lines = [lines;"";"The clean reconstruction uses contract v4 natural-dimensional, pre-scaled coefficient data, specialized straight-line assembly/projection, native compiler optimization, and two transient coefficient workers. The experimental branch remains the component-ablation record; this artifact verifies the reconstructed cumulative implementation.";""];
markdown = join(lines,newline);
end

function records = sourceHashes(repositoryRoot)
paths = [ ...
    "CompiledKernel/include/WaveVortexKernel/WVKernelTypes.hpp"; ...
    "CompiledKernel/src/WVKernelTypes.cpp"; ...
    "CompiledKernel/include/WaveVortexKernel/WVTransformConstantStratificationKernel.hpp"; ...
    "CompiledKernel/src/WVTransformConstantStratificationKernel.cpp"; ...
    "Benchmarks/buildCompiledKernelTransformMex.m"; ...
    "Benchmarks/compiled-kernel/wv_compiled_transform_mex.cpp"];
records = repmat(struct("path","","sha256",""),numel(paths),1);
for iPath = 1:numel(paths)
    records(iPath) = struct("path",paths(iPath),"sha256",sha256File(fullfile(repositoryRoot,paths(iPath))));
end
end

function [commit,tree,isDirty] = gitIdentity(root)
[status,commit] = system(sprintf('git -C "%s" rev-parse HEAD',root));
if status ~= 0, error("WaveVortexModel:GitIdentity","Unable to identify the candidate commit."); end
[status,tree] = system(sprintf('git -C "%s" rev-parse HEAD^{tree}',root));
if status ~= 0, error("WaveVortexModel:GitIdentity","Unable to identify the candidate tree."); end
[status,changes] = system(sprintf('git -C "%s" status --porcelain --untracked-files=no',root));
if status ~= 0, error("WaveVortexModel:GitIdentity","Unable to inspect the candidate tree."); end
commit = string(strtrim(commit)); tree = string(strtrim(tree)); isDirty = strlength(strtrim(string(changes)))>0;
end

function path = defaultBaselineArtifact
path = fullfile(fileparts(mfilename("fullpath")),"results","experiments","issue137","20260811T175649956Z-maca64-r2026a","native-fftw-baseline.json");
end

function path = relativePath(path,root)
path = erase(string(path),string(root)+filesep);
end

function hash = sha256File(pathname)
[status,output] = system(sprintf('/usr/bin/shasum -a 256 "%s"',pathname));
if status ~= 0, error("WaveVortexModel:HashFailure","Unable to hash %s.",pathname); end
hash = extractBefore(string(strtrim(output))," ");
end

function writeText(pathname,value)
fileId = fopen(pathname,"w");
if fileId < 0, error("WaveVortexModel:ArtifactWriteFailed","Unable to write %s.",pathname); end
cleanup = onCleanup(@()fclose(fileId));
fprintf(fileId,"%s",value);
clear cleanup
end

function value = utcTimestamp
value = string(datetime("now","TimeZone","UTC","Format","yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end

function value = conditional(condition,trueValue,falseValue)
if condition, value = trueValue; else, value = falseValue; end
end
