function freeSurfaceQGCoefficientStorageBenchmarkWorker(configPath,outputPath)
% Fresh-process worker for the free-surface QG storage benchmark.
config = jsondecode(fileread(configPath));
try
    result = runFreeSurfaceQGCoefficientStorageBenchmark( ...
        gridIds=string(config.gridId),endpointIds=string(config.endpointId), ...
        strategyIds=string(config.strategyId),seed=config.seed, ...
        smallNxyz=config.smallNxyz,representativeNxyz=config.representativeNxyz, ...
        representativeNj=config.representativeNj,mdaGramTolerance=config.mdaGramTolerance,Lxyz=config.Lxyz, ...
        warmupCount=config.warmupCount,sampleCount=config.sampleCount, ...
        bootstrapCount=config.bootstrapCount, ...
        minimumMeaningfulSpeedup=config.minimumMeaningfulSpeedup, ...
        shouldUseFreshProcess=false,phasePath=string(config.phasePath), ...
        plateauSeconds=config.plateauSeconds);
    payload = struct("status","complete","strategy",result.cases(1).strategies(1),"failure","");
catch exception
    payload = struct( ...
        "status","failed","strategy",struct(), ...
        "failure",string(getReport(exception,"extended","hyperlinks","off")));
end
fileId = fopen(outputPath,"w");
cleanup = onCleanup(@()fclose(fileId));
fprintf(fileId,"%s",jsonencode(payload));
clear cleanup
end
