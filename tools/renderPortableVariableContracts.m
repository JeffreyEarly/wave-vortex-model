function text = renderPortableVariableContracts(catalog)
% Render configuration metadata and dependency ordinals from one catalog.
lines = ["// Generated by tools/generatePortableVariableCatalog.m. Do not edit."; ...
    "#pragma once";"#include ""WVPortableVariableCatalog.hpp"""; ...
    "namespace wavevortex::runtime {"; ...
    "enum class WVPortableDiagnosticRuntime : std::uint8_t { implemented, pending305, pending315, intentionalIncompatibility };"; ...
    "enum class WVPortableFlowComponent : std::uint8_t { total, geostrophic, wave, inertial, mda };"; ...
    "struct WVPortableVariableContract {"; ...
    "  const char *configuration;"; ...
    "  WVPortableVariableMetadata metadata;"; ...
    "  std::array<WVPortableVariable, 8> dependencies;"; ...
    "  std::uint8_t dependencyCount;"; ...
    "  WVPortableVariable trueProfileDependency;"; ...
    "  std::uint64_t intermediateMask;"; ...
    "  WVPortableDiagnosticRuntime runtime;"; ...
    "  const char *authority;"; ...
    "  const char *operationClass;"; ...
    "  const char *operationExpression;"; ...
    "  WVPortableFlowComponent component;"; ...
    "  std::array<const char *, 3> netCDFCoordinateRoles;"; ...
    "  const char *samplingRestriction;"; ...
    "  const char *configurationRestriction;"; ...
    "};"; ...
    "inline constexpr std::array<std::string_view, " + numel(catalog.configurations) + "> WVPortableVariableConfigurations{{"; ...
    "  " + join(arrayfun(@quote,catalog.configurations),", ");"}};"; ...
    "struct WVPortableVariableConfiguration { std::string_view id; std::string_view transformClass; bool isHydrostatic; bool shouldAntialias; };"; ...
    "inline constexpr std::array<WVPortableVariableConfiguration, " + numel(catalog.configurations) + "> WVPortableVariableConfigurationMetadata{{"];
for row = reshape(catalog.configurationMetadata,1,[])
    lines(end+1) = "  {" + quote(row.id) + ", " + quote(row.transformClass) + ", " + boolean(row.isHydrostatic) + ", " + boolean(row.shouldAntialias) + "},"; %#ok<AGROW>
end
lines = [lines;"}};";"inline constexpr std::array<WVPortableVariableContract, " + numel(catalog.contracts) + "> WVPortableVariableContracts{{"];
for row = reshape(catalog.contracts,1,[])
    m = row.metadata;
    dimensions = [m.dimensions,strings(1,3-numel(m.dimensions))];
    attribute = "{"""", """"}";
    if ~isempty(m.netCDFAttributes)
        assert(isscalar(m.netCDFAttributes),"All annotation attributes must be represented.");
        attribute = "{" + quote(m.netCDFAttributes(1).name) + ", " + quote(m.netCDFAttributes(1).value) + "}";
    end
    metadata = "{WVPortableVariable::" + m.cppIdentifier + ", " + m.ordinal + ", " + quote(m.name) + ...
        ", {{" + join(arrayfun(@quote,dimensions),", ") + "}}, " + numel(m.dimensions) + ", " + ...
        quote(m.units) + ", " + quote(m.description) + ", " + boolean(m.isComplex) + ", " + ...
        boolean(m.isVariableWithLinearTimeStep) + ", " + boolean(m.isVariableWithNonlinearTimeStep) + ", " + ...
        boolean(m.isDependentOnApAmA0) + ", WVPortableVariableKind::" + m.portableKind + ...
        ", WVPortableNaturalRank::" + m.naturalRank + ", " + samplingMask(m.samplingModes) + ", " + ...
        string(m.primitiveDependencyMask) + ", " + string(m.movingPrimitiveChannel) + ", " + attribute + ", " + numel(m.netCDFAttributes) + "}";
    dependencies = arrayfun(@(n)identifier(n,catalog),row.dependencies);
    assert(numel(dependencies)<=8,"Increase the fixed dependency capacity explicitly.");
    dependencies = [dependencies,repmat("WVPortableVariable::invalid",1,8-numel(dependencies))];
    conditional = "WVPortableVariable::invalid";
    if ~isempty(row.trueProfileDependencies), conditional=identifier(row.trueProfileDependencies,catalog); end
    runtime = replace(row.runtimeStatus,["pending-305","pending-315","intentional-incompatibility"],["pending305","pending315","intentionalIncompatibility"]);
    component = row.component;
    if component=="", component="total"; end
    lines(end+1) = "  {" + quote(row.configuration) + ", " + metadata + ", {{" + join(dependencies,", ") + "}}, " + ...
        numel(row.dependencies) + ", " + conditional + ", " + string(row.intermediateMask) + ", WVPortableDiagnosticRuntime::" + runtime + ...
        ", " + join(arrayfun(@quote,[row.authority,row.operationClass,row.operationExpression]),", ") + ...
        ", WVPortableFlowComponent::" + component + ", {{" + join(arrayfun(@quote,dimensions),", ") + "}}, " + join(arrayfun(@quote,[row.samplingRestriction,row.configurationRestriction]),", ") + "},"; %#ok<AGROW>
end
lines = [lines;"}};"; ...
    "struct WVPortableVariableExclusion { std::string_view name; std::string_view reason; };"; ...
    "inline constexpr std::array<WVPortableVariableExclusion, " + numel(catalog.exclusions) + "> WVPortableVariableExclusions{{"];
for row = reshape(catalog.exclusions,1,[])
    lines(end+1) = "  {" + quote(row.name) + ", " + quote(row.reason) + "},"; %#ok<AGROW>
end
lines = [lines;"}};";"struct WVPortableIntermediate { std::string_view name; std::string_view lifetime; std::string_view description; };"; ...
    "inline constexpr std::array<WVPortableIntermediate, " + numel(catalog.intermediates) + "> WVPortableIntermediates{{"];
for row = reshape(catalog.intermediates,1,[])
    lines(end+1) = "  {" + quote(row.name) + ", " + quote(row.lifetime) + ", " + quote(row.description) + "},"; %#ok<AGROW>
end
lines = [lines;"}};"; ...
    "inline constexpr const WVPortableVariableContract *"; ...
    "portableVariableContract(WVPortableVariable id, std::string_view configuration) noexcept {"; ...
    "  for (const auto &row : WVPortableVariableContracts)"; ...
    "    if (row.metadata.identifier == id && configuration == row.configuration) return &row;"; ...
    "  return nullptr;";"}"; ...
    "inline constexpr std::size_t portableVariableContractBytes() noexcept {"; ...
    "  return sizeof(WVPortableVariableContracts) + sizeof(WVPortableVariableConfigurations) +"; ...
    "         sizeof(WVPortableVariableExclusions) + sizeof(WVPortableIntermediates) + sizeof(WVPortableVariableConfigurationMetadata);";"}"; ...
    "} // namespace wavevortex::runtime";""];
text = join(lines,newline);
end

function value = quote(value)
value = string(jsonencode(char(value)));
end

function value = boolean(value)
if value, value="true"; else, value="false"; end
end

function value = identifier(name,catalog)
index = find(string({catalog.variables.name}) == name,1);
value = "WVPortableVariable::" + catalog.variables(index).cppIdentifier;
end

function mask = samplingMask(modes)
mask = sum(2.^find(ismember(["coefficients","fullGrid","fixedVerticalProfiles","positions"],modes))/2);
mask = string(mask);
end
